#!/usr/bin/env python3
"""Embed the runtime assets into C arrays (no file system needed on the Vita)."""
import glob
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT_DIR = os.path.join(ROOT, "vita", "build", "generated")


def c_array(name: str, data: bytes) -> str:
    out = ["const unsigned char %s[] = {" % name]
    line = []
    for i, b in enumerate(data):
        line.append(str(b))
        if len(line) == 24:
            out.append(",".join(line) + ",")
            line = []
    if line:
        out.append(",".join(line) + ",")
    out.append("};")
    out.append("const unsigned int %s_len = %d;" % (name, len(data)))
    return "\n".join(out)


def main() -> int:
    os.makedirs(OUT_DIR, exist_ok=True)
    entries = [
        ("asset_shim_js", os.path.join(ROOT, "vita", "js", "shim.js")),
        ("asset_ui_js", os.path.join(ROOT, "vita", "js", "ui.js")),
        ("asset_font_ttf", os.path.join(ROOT, "vita", "assets", "font.ttf")),
    ]
    games = sorted(glob.glob(os.path.join(ROOT, "vita", "assets", "game_*.js")))
    if not games:
        print("ERROR: no game_*.js assets (run tools/extract_assets.py)", file=sys.stderr)
        return 1

    header = [
        "/* generated by tools/embed.py — do not edit */",
        "#ifndef HOLLOWDEEP_ASSETS_DATA_H",
        "#define HOLLOWDEEP_ASSETS_DATA_H",
        "typedef struct { const unsigned char *data; unsigned int len; } AssetBlob;",
    ]
    body = ['#include "assets_data.h"', ""]

    for name, path in entries:
        if not os.path.exists(path):
            print("ERROR: missing asset %s" % path, file=sys.stderr)
            return 1
        data = open(path, "rb").read()
        header.append("extern const unsigned char %s[];" % name)
        header.append("extern const unsigned int %s_len;" % name)
        header.append("extern const AssetBlob %s;" % name.replace("asset_", "blob_"))
        body.append(c_array(name, data))
        body.append("const AssetBlob %s = { %s, %s_len };" %
                    (name.replace("asset_", "blob_"), name, name))
        body.append("")

    header.append("extern const AssetBlob asset_game_scripts[];")
    header.append("extern const int asset_game_script_count;")
    header.append("#endif")

    script_names = []
    for i, path in enumerate(games):
        name = "asset_game_%02d_js" % i
        data = open(path, "rb").read()
        body.append(c_array(name, data))
        body.append("")
        script_names.append(name)
    body.append("const AssetBlob asset_game_scripts[] = {")
    for name in script_names:
        body.append("{ %s, %s_len }," % (name, name))
    body.append("};")
    body.append("const int asset_game_script_count = %d;" % len(games))

    with open(os.path.join(OUT_DIR, "assets_data.h"), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(header) + "\n")
    with open(os.path.join(OUT_DIR, "assets_data.c"), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(body) + "\n")
    total = sum(os.path.getsize(p) for p in games)
    print("embedded %d game scripts (%.1f KB)" % (len(games), total / 1024.0))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
